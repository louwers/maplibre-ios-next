#!/usr/bin/env bash
# Builds the C API from a maplibre-native-ffi checkout on maplibre-native-next
# (src/next) for iOS devices and simulators, as a local stand-in for the
# maplibre-native-next-ffi-distribution package:
#
#   scripts/build-local-ffi.sh ~/src/maplibre-native-ffi
#   MLN_LOCAL_FFI=1 xcodebuild -scheme MapLibreNext ...
#
# With MLN_LOCAL_FFI set, Package.swift depends on .local-ffi/ instead of the
# published package. The checkout needs what its own builds need (cargo,
# cargo-about, zig, ninja, the third_party/maplibre-native headers).
set -euo pipefail

ffi="$(cd "${1:?usage: $0 <maplibre-native-ffi checkout>}" && pwd)"
root="$(cd "$(dirname "$0")/.." && pwd)"
package="$root/.local-ffi/maplibre-native-next-ffi-distribution"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

frameworks=()
for preset in ios-arm64-metal-next ios-simulator-arm64-metal-next; do
  if [[ ! -f "$ffi/build/$preset/CMakeCache.txt" ]]; then
    (cd "$ffi" && cmake --preset "$preset")
  fi
  # The install step needs the whole build, not only the framework.
  cmake --build "$ffi/build/$preset"
  cmake --install "$ffi/build/$preset" --prefix "$work/$preset" >/dev/null
  frameworks+=(-framework "$work/$preset/Frameworks/MaplibreNativeC.framework")
done

rm -rf "$package"
mkdir -p "$package"
xcodebuild -create-xcframework "${frameworks[@]}" \
  -output "$package/MaplibreNativeC.xcframework" >/dev/null
cat >"$package/Package.swift" <<'EOF'
// swift-tools-version: 5.9
// Generated by scripts/build-local-ffi.sh.
import PackageDescription

let package = Package(
  name: "maplibre-native-next-ffi",
  platforms: [.iOS("15.0")],
  products: [.library(name: "MaplibreNativeC", targets: ["MaplibreNativeC"])],
  targets: [.binaryTarget(name: "MaplibreNativeC", path: "MaplibreNativeC.xcframework")]
)
EOF
echo "Built $package from $(git -C "$ffi" rev-parse --short HEAD) in $ffi"
