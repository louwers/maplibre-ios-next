"""Generates the runtime coverage test from classic MapLibre iOS's public API.

For every class, category and exported symbol in the public headers, the test
checks at runtime that the implementation provides it:
  - classes: NSClassFromString;
  - protocols: objc_getProtocol;
  - methods and property accessors, including the required members of the
    product's protocols that a class adopts: (instances)RespondToSelector;
  - extern constants and non-inline functions: dlsym.
The test writes every result to coverage.json in the parity output directory.
Run with python3 -I.
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import objc_api  # noqa: E402


def protocol_requirements(api, protocol, seen=None):
    """Required instance and class selectors of a product protocol and its parents."""
    seen = seen or set()
    if protocol in seen or protocol not in api["protocols"]:
        return []
    seen.add(protocol)
    entry = api["protocols"][protocol]
    selectors = []
    for key, method in entry["methods"].items():
        if not method["optional"] and not method["unavailable"]:
            selectors.append((key[0], key[1:]))
    for prop in entry["properties"].values():
        if prop["optional"] or prop["unavailable"]:
            continue
        kind = "+" if prop["class"] else "-"
        selectors.append((kind, prop["getter"]))
        if prop["setter"]:
            selectors.append((kind, prop["setter"]))
    for parent in entry["protocols"]:
        selectors += protocol_requirements(api, parent, seen)
    return selectors


def checks(api):
    """(kind, owner, name, source) tuples to verify at runtime."""
    result = []
    for name, entry in sorted(api["classes"].items()):
        if entry["unavailable"]:
            continue
        result.append(("class", name, name, "class"))

        def members(owner, entry, source):
            for key, method in sorted(entry["methods"].items()):
                if not method["unavailable"]:
                    result.append(("selector" if key[0] == "-" else "classSelector", owner, key[1:], source))
            for prop_name, prop in sorted(entry["properties"].items()):
                if prop["unavailable"]:
                    continue
                kind = "classSelector" if prop["class"] else "selector"
                result.append((kind, owner, prop["getter"], source + " property " + prop_name))
                if prop["setter"]:
                    result.append((kind, owner, prop["setter"], source + " property " + prop_name))

        members(name, entry, "class")
        for protocol in entry["protocols"]:
            for kind, selector in protocol_requirements(api, protocol):
                result.append(("selector" if kind == "-" else "classSelector", name, selector,
                               "protocol " + protocol))
    for name, entry in sorted(api["categories"].items()):
        owner = entry["class"]
        for key, method in sorted(entry["methods"].items()):
            if not method["unavailable"]:
                result.append(("selector" if key[0] == "-" else "classSelector", owner, key[1:], "category " + name))
        for prop_name, prop in sorted(entry["properties"].items()):
            if prop["unavailable"]:
                continue
            kind = "classSelector" if prop["class"] else "selector"
            result.append((kind, owner, prop["getter"], "category " + name + " property " + prop_name))
            if prop["setter"]:
                result.append((kind, owner, prop["setter"], "category " + name + " property " + prop_name))
    for name, entry in sorted(api["protocols"].items()):
        result.append(("protocol", name, name, "protocol"))
    for name, entry in sorted(api["functions"].items()):
        if not entry["inline"] and not entry["unavailable"]:
            result.append(("symbol", "", name, "function"))
    for name, entry in sorted(api["variables"].items()):
        if not entry["unavailable"]:
            result.append(("symbol", "", name, "variable"))
    # Unique, stable order.
    seen, unique = set(), []
    for check in result:
        key = check[:3]
        if key not in seen:
            seen.add(key)
            unique.append(check)
    return unique


def objc_string(text):
    return '@"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(entries, known_gaps):
    lines = [
        "// Generated by Parity/api/gen_coverage.py from classic MapLibre iOS's public",
        "// headers. Do not edit.",
        "",
        "#import <XCTest/XCTest.h>",
        "#import <dlfcn.h>",
        "#import <objc/runtime.h>",
        "@import MapLibre;",
        "",
        '#import "ParityRecorder.h"',
        "",
        "typedef struct {",
        "  const char *kind;",
        "  const char *owner;",
        "  const char *name;",
        "  const char *source;",
        "} MLNParityCoverageCheck;",
        "",
        "static const MLNParityCoverageCheck MLNParityCoverageChecks[] = {",
    ]
    for kind, owner, name, source in entries:
        lines.append(f'  {{"{kind}", "{owner}", "{name}", "{source}"}},')
    lines += [
        "};",
        "",
        "// Symbols that classic MapLibre iOS itself does not provide at runtime.",
        "static NSSet<NSString *> *MLNParityCoverageKnownClassicGaps(void) {",
        "  return [NSSet setWithArray:@[",
    ]
    for gap in sorted(known_gaps):
        lines.append(f"    {objc_string(gap)},")
    lines += [
        "  ]];",
        "}",
        "",
        "static BOOL MLNParityCoverageCheckPasses(const MLNParityCoverageCheck *check) {",
        "  NSString *kind = @(check->kind);",
        "  if ([kind isEqualToString:@\"class\"]) {",
        "    return NSClassFromString(@(check->name)) != nil;",
        "  }",
        "  if ([kind isEqualToString:@\"protocol\"]) {",
        "    return objc_getProtocol(check->name) != NULL;",
        "  }",
        "  if ([kind isEqualToString:@\"symbol\"]) {",
        "    return dlsym(RTLD_DEFAULT, check->name) != NULL;",
        "  }",
        "  Class owner = NSClassFromString(@(check->owner));",
        "  SEL selector = sel_registerName(check->name);",
        "  if ([kind isEqualToString:@\"selector\"]) {",
        "    return [owner instancesRespondToSelector:selector];",
        "  }",
        "  return [owner respondsToSelector:selector];",
        "}",
        "",
        "@interface MLNAPICoverageTests : XCTestCase",
        "@end",
        "",
        "@implementation MLNAPICoverageTests",
        "",
        "- (void)testPublicAPIIsImplemented {",
        "  NSSet *knownGaps = MLNParityCoverageKnownClassicGaps();",
        "  NSMutableArray *results = [NSMutableArray array];",
        "  NSMutableArray *missing = [NSMutableArray array];",
        "  NSUInteger count = sizeof(MLNParityCoverageChecks) / sizeof(MLNParityCoverageChecks[0]);",
        "  for (NSUInteger i = 0; i < count; i++) {",
        "    const MLNParityCoverageCheck *check = &MLNParityCoverageChecks[i];",
        "    NSString *identifier = [NSString stringWithFormat:@\"%s %s%s%s\", check->kind, check->owner,",
        "                                                     *check->owner ? \" \" : \"\", check->name];",
        "    BOOL passes = MLNParityCoverageCheckPasses(check);",
        "    BOOL known = [knownGaps containsObject:identifier];",
        "    [results addObject:@{",
        "      @\"id\" : identifier,",
        "      @\"source\" : @(check->source),",
        "      @\"present\" : @(passes),",
        "      @\"knownClassicGap\" : @(known),",
        "    }];",
        "    if (!passes && !known) {",
        "      [missing addObject:identifier];",
        "    }",
        "  }",
        "  [ParityRecorder writeJSON:@{@\"checks\" : results, @\"total\" : @(count), @\"missing\" : missing}",
        "                    toFile:@\"coverage.json\"];",
        "  XCTAssertEqual(missing.count, 0u, @\"%lu of %lu API symbols are missing at runtime: %@\",",
        "                 (unsigned long)missing.count, (unsigned long)count,",
        "                 [[missing subarrayWithRange:NSMakeRange(0, MIN(missing.count, 50u))]",
        "                     componentsJoinedByString:@\", \"]);",
        "}",
        "",
        "@end",
        "",
    ]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--ast", required=True)
    p.add_argument("--headers", required=True)
    p.add_argument("--known-gaps", required=True)
    p.add_argument("--out", required=True)
    args = p.parse_args()
    api = objc_api.collect(args.ast, args.headers)
    entries = checks(api)
    with open(args.known_gaps, encoding="utf-8") as f:
        known = json.load(f)["gaps"]
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(render(entries, [g["id"] for g in known]))
    print(f"{len(entries)} checks: {len(api['classes'])} classes, {len(api['categories'])} categories, "
          f"{len(api['protocols'])} protocols, {len(api['functions'])} functions, {len(api['variables'])} variables")


if __name__ == "__main__":
    main()
